/**
 * Cross-check of TypeScript solvers A and B against the Python oracle (spec §5.4).
 *
 * Run the oracle first:
 *   python tools/oracle/kinematics.py tools/oracle/out/oracle.json \
 *     tests/golden/golden.json tests/fixtures/euskadi2020.json tests/oracle/random-chains.json
 * Locally the test is skipped if the oracle output is missing; in CI
 * (ORACLE_REQUIRED=1) a missing file is a failure.
 *
 * GEN_ORACLE_CASES=1 regenerates tests/oracle/random-chains.json (fixed seed).
 */
import fc from 'fast-check';
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { chainArb } from './arbitraries';
import { ARCHETYPES, generate } from '../src/core/generator';
import { type ChainJSON, type StateSolution, allStates, chainFromJSON, chainToJSON, stateKey } from '../src/core/model';
import * as R from '../src/core/rational';
import { solveStateB } from '../src/core/solverLinear';
import { solveStateA } from '../src/core/solverPath';

const ROOT = resolve(__dirname, '..');
const OUT = resolve(ROOT, 'tools/oracle/out/oracle.json');
const RANDOM = resolve(ROOT, 'tests/oracle/random-chains.json');
const GENERATED = resolve(ROOT, 'tests/oracle/generated-chains.json');
const POOL = ['src/data/pool/ope-euskadi-2020.json', 'src/data/pool/generated.json', 'src/data/pool/basics.json', 'src/data/pool/ope-madrid-2025.json', 'src/data/pool/adapted.json', 'src/data/pool/ope-murtzia-2021.json', 'src/data/pool/ope-gaztela-leon-2020.json', 'src/data/pool/ope-gaztela-leon-2018.json', 'src/data/pool/ope-valentzia-2025.json', 'src/data/pool/ope-murtzia-2023.json'].map((p) => resolve(ROOT, p));

interface OracleState {
  ok: boolean;
  shafts?: Record<string, { n: string; dir: 1 | -1 | null }>;
  linear?: Record<string, { coef: string; piPower: number }>;
}

function normalise(s: StateSolution): OracleState {
  if (!s.ok) return { ok: false };
  return {
    ok: true,
    shafts: Object.fromEntries(Object.entries(s.shafts).map(([k, v]) => [k, { n: R.toString(v.n), dir: v.dir }])),
    linear: Object.fromEntries(Object.entries(s.linear).map(([k, v]) => [k, { coef: R.toString(v.v.coef), piPower: v.v.piPower }])),
  };
}

function inputChains(): [string, ChainJSON][] {
  const g = JSON.parse(readFileSync(resolve(ROOT, 'tests/golden/golden.json'), 'utf8')) as { cases: { id: string; chain?: ChainJSON }[] };
  const fx = JSON.parse(readFileSync(resolve(ROOT, 'tests/fixtures/euskadi2020.json'), 'utf8')) as { chain: ChainJSON };
  const rnd = JSON.parse(readFileSync(RANDOM, 'utf8')) as { chains: { id: string; chain: ChainJSON }[] };
  const gen = JSON.parse(readFileSync(GENERATED, 'utf8')) as { chains: { id: string; chain: ChainJSON }[] };
  const pool: [string, ChainJSON][] = POOL.flatMap((p) => {
    const d = JSON.parse(readFileSync(p, 'utf8')) as { id?: string; chain?: ChainJSON; exercises?: { id: string; chain: ChainJSON }[] };
    return d.exercises ? d.exercises.map((e) => [e.id, e.chain] as [string, ChainJSON]) : [[d.id as string, d.chain as ChainJSON]];
  });
  return [
    ...pool,
    ...gen.chains.map((c) => [c.id, c.chain] as [string, ChainJSON]),
    ...g.cases.filter((c) => c.chain).map((c) => [c.id, c.chain as ChainJSON] as [string, ChainJSON]),
    ['euskadi2020', fx.chain],
    ...rnd.chains.map((c) => [c.id, c.chain] as [string, ChainJSON]),
  ];
}

describe('oracle', () => {
  it.runIf(!!process.env.GEN_ORACLE_CASES)('regenerate random oracle cases', () => {
    const chains = fc.sample(chainArb({ clusters: true, loops: true, consistentLoops: true, maxShafts: 7 }), { seed: 20261119, numRuns: 400 });
    mkdirSync(resolve(ROOT, 'tests/oracle'), { recursive: true });
    writeFileSync(RANDOM, JSON.stringify({ _comment: 'Generated by tests/oracle.test.ts (GEN_ORACLE_CASES=1, seed 20261119).', chains: chains.map((chain, i) => ({ id: `R${i}`, chain })) }));
    // a sample of generator output (30 seeds per archetype)
    const gen = ARCHETYPES.flatMap((a) => Array.from({ length: 30 }, (_, s) => ({ id: `G-${a.id}-${s}`, chain: chainToJSON(generate(a.id, s).chain) })));
    writeFileSync(GENERATED, JSON.stringify({ _comment: 'Generator sample for the oracle (GEN_ORACLE_CASES=1).', chains: gen }));
  });

  const have = existsSync(OUT);
  if (!have && process.env.ORACLE_REQUIRED) it('oracle output exists', () => expect(have).toBe(true));

  it.runIf(have)('A and B agree with the Python oracle on every chain and state', () => {
    const oracle = JSON.parse(readFileSync(OUT, 'utf8')) as { chains: Record<string, Record<string, OracleState>> };
    let compared = 0;
    for (const [id, j] of inputChains()) {
      const c = chainFromJSON(j);
      const o = oracle.chains[id];
      expect(o, `oracle has no result for ${id}`).toBeDefined();
      for (const st of allStates(c)) {
        const key = stateKey(c, st);
        const want = (o as Record<string, OracleState>)[key];
        expect(want, `${id} ${key}`).toBeDefined();
        expect(normalise(solveStateA(c, st)), `A ${id} ${key}`).toEqual(want);
        expect(normalise(solveStateB(c, st)), `B ${id} ${key}`).toEqual(want);
        compared++;
      }
    }
    expect(compared).toBeGreaterThan(400);
  });
});
